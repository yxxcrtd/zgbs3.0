--2.日间交易表
select A.FINPROD_ID||'',''||A.TRADE_ID AS RKEY, A.UNIT_CPRICE AS RVALUE
from TRD_PRODUCT_TEMP_DEAL  A
inner join TRD_PRODUCT_TEMP_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and NVL(A.IS_CANCEL,''N'') =''N''
