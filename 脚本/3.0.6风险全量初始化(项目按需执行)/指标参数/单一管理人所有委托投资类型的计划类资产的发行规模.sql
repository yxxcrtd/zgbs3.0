V_CONTENT_01_02_03 CLOB := 'WITH PLANNET AS (
    -- 计划类资产净值
    SELECT FPV.FINPROD_ID,FPV.VALUATION  FROM FIN_PRODUCT_VALUATION FPV
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FPV.FINPROD_ID
    LEFT JOIN (
        SELECT FINPROD_ID, MAX(VAL_DATE) VAL_DATE FROM FIN_PRODUCT_VALUATION
        WHERE VAL_DATE <= DATE ''${valDate}'' - 1
        GROUP BY FINPROD_ID
    ) FPVMAX ON FPVMAX.FINPROD_ID = FPV.FINPROD_ID AND FPVMAX.VAL_DATE = FPV.VAL_DATE
    WHERE FPV.FINPROD_TYPE2 = ''F17'' AND FPT.TYPE_10 = ''N001''
)
SELECT NVL(SUM(NVL(FP.ISSUE_AMT,0) * NVL(PLANNET.VALUATION,1)), 0) RVALUE, FP.MANAGER RKEY
FROM FIN_PRODUCT FP
LEFT JOIN PLANNET ON PLANNET.FINPROD_ID = FP.FINPROD_ID
INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
WHERE FP.FINPROD_TYPE2 = ''F17'' AND FPT.TYPE_10 = ''N001''
