	nvl(SUM(nvl(PTL_SEC_VALUTION.TDY_FLOAT_INGPL, 0) + nvl(PTL_SEC_VALUTION.DSC_COST_AMT, 0)+nvl(PTL_SEC_VALUTION.TDY_INTINCEXP, 0)+nvl(PTL_SEC_VALUTION.DELAY_PAY_AMT, 0)),0) AS MKT,
	FIN_PRODUCT_TYPE.TYPE_4 windAssetType,
	FIN_PRODUCT_TYPE.TYPE_5 windAssetType2,
	FIN_PRODUCT_TYPE.TYPE_6 assetType,
	FIN_PRODUCT_TYPE.TYPE_7 assetType2,
	FIN_PRODUCT_ADD.INVEST_NATURE investNature,
	REP_ASSET_DEPT.REP_ASSET_TYPE deptType,
	REP_ASSET_DEPT.REP_ASSET_TYPE deptType2,
	PTL_SEC_VALUTION.FINPROD_ID finprodId,
	FIN_PRODUCT.ISSUER issuer,
	MST_CUSTOMER_INFO.INDUSTRY industry,
	MST_CUSTOMER_INFO.INDUSTRY2 industry2,
	ZXRATING.GRADE_RESULT bondGradeType,
	ZTRATING.GRADE_RESULT bodyGradeType, PTL_SEC_VALUTION.PORTFOLIO_ID PORTFOLIO_ID,
	FIN_PRODUCT.MDATE mdate
	FROM PTL_SEC_VALUTION
	LEFT JOIN FIN_PRODUCT ON PTL_SEC_VALUTION.FINPROD_ID = FIN_PRODUCT.FINPROD_ID
	LEFT JOIN (SELECT s1.*,s2.INDUSTRY,s2.INDUSTRY2 FROM MST_CUSTOMER_INFO s1 INNER JOIN MST_CUSTOMER_INFO_ADD s2 ON s1.CUSTOMER_ID=s2.CUSTOMER_ID) MST_CUSTOMER_INFO ON FIN_PRODUCT.ISSUER = MST_CUSTOMER_INFO.CUSTOMER_ID
	LEFT JOIN FIN_PRODUCT_TYPE ON PTL_SEC_VALUTION.FINPROD_ID = FIN_PRODUCT_TYPE.FINPROD_ID
	LEFT JOIN FIN_PRODUCT_ADD ON FIN_PRODUCT_ADD.FINPROD_ID = PTL_SEC_VALUTION.FINPROD_ID
	LEFT JOIN REP_ASSET_DEPT ON PTL_SEC_VALUTION.FINPROD_ID = REP_ASSET_DEPT.REP_FINPROD_ID
	LEFT JOIN (SELECT * FROM (SELECT O_CODE,GRADE_RESULT,ROW_NUMBER() OVER(PARTITION BY O_CODE ORDER BY CREATE_TIME desc) AS rn FROM MST_BOND_CREDIT_RATING T WHERE O_TYPE = ''02'' AND GRADE_DATE<=DATE ''${valDate}'') where rn=1 ) ZXRATING ON ZXRATING.O_CODE = PTL_SEC_VALUTION.FINPROD_ID
	LEFT JOIN (SELECT * FROM (SELECT O_CODE,GRADE_DATE,GRADE_RESULT,ROW_NUMBER() OVER(PARTITION BY O_CODE ORDER BY CREATE_TIME desc) AS rn FROM MST_BOND_CREDIT_RATING T WHERE O_TYPE = ''01'' AND GRADE_DATE<=DATE ''${valDate}'') where rn=1 ) ZTRATING ON ZTRATING.O_CODE = PTL_SEC_VALUTION.FINPROD_ID
	WHERE PTL_SEC_VALUTION.PORTFOLIO_ID IN ${portfolioCode} AND PTL_SEC_VALUTION.CDATE = DATE ''${valDate}''
	GROUP BY
	PTL_SEC_VALUTION.PORTFOLIO_ID,FIN_PRODUCT_TYPE.TYPE_4,FIN_PRODUCT_TYPE.TYPE_5,FIN_PRODUCT_TYPE.TYPE_6,FIN_PRODUCT_TYPE.TYPE_7,FIN_PRODUCT_ADD.INVEST_NATURE,REP_ASSET_DEPT.REP_ASSET_TYPE,
	PTL_SEC_VALUTION.FINPROD_ID,FIN_PRODUCT.ISSUER,MST_CUSTOMER_INFO.INDUSTRY,MST_CUSTOMER_INFO.INDUSTRY2,ZXRATING.GRADE_RESULT,ZTRATING.GRADE_RESULT,FIN_PRODUCT.MDATE';

