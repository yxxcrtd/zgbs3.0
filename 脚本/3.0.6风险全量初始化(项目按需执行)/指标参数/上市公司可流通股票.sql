V_CONTENT_04 CLOB := 'SELECT RVALUE,RKEY,RKEYCN FROM (
  SELECT (SELECT nvl(sum(s.C_SHARES),0) FROM MST_SHARE_PRICE s WHERE s.SHARES_ID=t2.FINPROD_MARKET_ID AND s.DEAL_DATE=(
