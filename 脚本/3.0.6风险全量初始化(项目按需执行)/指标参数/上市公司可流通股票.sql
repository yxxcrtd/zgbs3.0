DECLARE
----实时、买入预占、卖出预占
V_CONTENT_01_02_03 CLOB := 'SELECT (SELECT nvl(sum(s.C_SHARES),0) FROM MST_SHARE_PRICE s WHERE s.SHARES_ID=t2.FINPROD_MARKET_ID AND s.DEAL_DATE=(
    SELECT max(DEAL_DATE) FROM MST_SHARE_PRICE m WHERE m.SHARES_ID=t2.FINPROD_MARKET_ID and m.DEAL_DATE<=date''${valDate}'')
  ) AS RVALUE,
    T2.FINPROD_ID RKEY
  from FIN_PRODUCT t2
  inner join FIN_PRODUCT_TYPE fpt on t2.FINPROD_ID=fpt.FINPROD_ID AND fpt.BRANCH=0 and fpt.TYPE_8 =''F11''
  GROUP BY T2.FINPROD_ID,T2.FINPROD_MARKET_ID';

