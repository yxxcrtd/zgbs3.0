    (
        SELECT
           NVL(m.MARKET_VALUE,0)+nvl(m.TDY_INTINCEXP, 0) RVALUE,M.FINPROD_ID
        FROM PTL_SEC_PIERCE_VALUTION M
        INNER JOIN FIN_PRODUCT_TYPE T3 ON M.FINPROD_ID = T3.FINPROD_ID
        AND (
        (T3.TYPE_8 in (''F01'',''F17'') AND (T3.TYPE_6 NOT IN (''B01'',''B03'',''B05'',''B14'',''B15'') OR (T3.TYPE_6 = ''B05'' AND T3.TYPE_7 != ''01'')) )
         OR T3.TYPE_8 NOT IN (''F01'',''F17'',''F11'',''F37'')
         )
        AND M.CDATE = date''${valDate}'' AND M.PORTFOLIO_ID IN ${portfolioCode}
               union all
               
               select ztg.RVALUE,ztg.FINPROD_ID from (
              --债券转托管转出方
                 SELECT  nvl(T.TRADE_AMT*-1,0) RVALUE,T.FINPROD_ID
                  FROM TRD_PRODUCT_DEAL T
                 INNER JOIN TRD_PRODUCT_DEAL_ADD T1 ON T.trade_id = T1.trade_id
                 INNER JOIN TRD_FIN_PRODUCT_DEAL_TOTAL T4 on T.TOTLE_TRADE_ID = T4.TOTLE_TRADE_ID
                 WHERE 
                    T.PS  IN ( ''Z01'')
                   AND T.TRADE_STATUS = ''01''
                   AND T.IS_CANCEL = ''N''
                   AND T.TRADE_DATE <= DATE''${valDate}''
                   AND T1.PORTFOLIO_ID IN ${portfolioCode}
                   AND NOT EXISTS (
                      -- 没有后续申购确认交易
                      SELECT 1 FROM TRD_PRODUCT_DEAL TRD WHERE T4.TOTLE_TRADE_ID = TRD.B_TRADE_ID AND TRD.TRADE_STATUS = ''01'' AND TRD.IS_CANCEL = ''N''
                )
                union all
              --发行人债券转托管转入方
                 SELECT  nvl(T.PRIN_AMT,0)RVALUE,T.FINPROD_ID
                  FROM TRD_FIN_PRODUCT_BARTER T
                 INNER JOIN TRD_PRODUCT_DEAL T4 ON T.trade_id = T4.trade_id
                 INNER JOIN TRD_PRODUCT_DEAL_ADD T1 ON T4.trade_id = T1.trade_id
                 INNER JOIN TRD_FIN_PRODUCT_DEAL_TOTAL T5 on T4.TOTLE_TRADE_ID = T5.TOTLE_TRADE_ID
                 WHERE 
                    T4.PS  IN ( ''Z01'')
                   AND T4.TRADE_STATUS = ''01''
                   AND T4.IS_CANCEL = ''N''
                   AND T4.TRADE_DATE <= DATE''${valDate}''
                   AND T1.PORTFOLIO_ID IN ${portfolioCode}
                   AND NOT EXISTS (
                      -- 没有后续申购确认交易
                      SELECT 1 FROM TRD_PRODUCT_DEAL TRD WHERE T5.TOTLE_TRADE_ID = TRD.B_TRADE_ID AND TRD.TRADE_STATUS = ''01'' AND TRD.IS_CANCEL = ''N''
                        )   
                 )ztg  INNER JOIN FIN_PRODUCT_TYPE T3 ON ztg.FINPROD_ID = T3.FINPROD_ID
                AND (T3.TYPE_8 in (''F01'',''F17'') AND (T3.TYPE_6 NOT IN (''B01'',''B03'',''B05'',''B14'',''B15'') OR (T3.TYPE_6 = ''B05'' AND T3.TYPE_7 != ''01'')) ) 
                 UNION ALL
                --场外货币基金、货币资管计划申购申请未确认的交易金额(+)、（场外货币基金、货币资管计划）赎回申请未确认的交易金额（-）
                 SELECT case when ps IN (''T04'') then nvl(T.TRADE_AMT,0)  else nvl(-1*T.TRADE_AMT,0) end  RVALUE,T.FINPROD_ID
                  FROM TRD_PRODUCT_DEAL T
                 INNER JOIN TRD_PRODUCT_DEAL_ADD T1 ON T.trade_id = T1.trade_id
                INNER JOIN FIN_PRODUCT_TYPE T3 ON T.FINPROD_ID = T3.FINPROD_ID
                 INNER JOIN FIN_PRODUCT T2 on T.FINPROD_ID = T2.FINPROD_ID
                 WHERE 
                    T.PS  IN (''T04'',''T06'')
                   AND (T3.TYPE_8 IN (''F09'') OR (T3.TYPE_8 = ''F02'' and T2.TRADE_MARKET = ''09'' and T3.TYPE_6=''F01''))
                   AND T.TRADE_STATUS = ''01''
                   AND T.IS_CANCEL = ''N''
                   AND T.TRADE_DATE <= DATE''${valDate}''
                   AND T1.PORTFOLIO_ID IN ${portfolioCode}
                   AND NOT EXISTS (
                      -- 没有后续申购确认交易
                      SELECT 1 FROM TRD_PRODUCT_DEAL TRD WHERE T.TRADE_ID = TRD.B_TRADE_ID AND TRD.TRADE_STATUS = ''01'' AND TRD.IS_CANCEL = ''N''   
                         )

                UNION ALL
               --场外非货币基金、净值资管计划申购申请未确认的交易金额(+)、（场外非货币基金、净值资管计划赎回申请未确认的交易金额（-）
                 SELECT case when ps IN (''T06'') and T.TRADE_AMT !=0  then nvl(-1*T.TRADE_AMT,0)
                  when ps IN (''T06'') and (T.TRADE_AMT =0 or T.TRADE_AMT is null)  then nvl(T.SHARE_AMT*-1,0)*(select NVL(fvpp.VALUATION,1) from  FIN_PRODUCT_VALUATION fvpp 
                 inner JOIN (select fvp.FINPROD_ID,MAX(fvp.VAL_DATE) VAL_DATE from FIN_PRODUCT_VALUATION fvp where fvp.VAL_DATE<=DATE''${valDate}'' group by fvp.FINPROD_ID) hq on fvpp.FINPROD_ID = hq.FINPROD_ID and fvpp.VAL_DATE = hq.VAL_DATE 
                 where fvpp.FINPROD_ID = T2.FINPROD_MARKET_ID)
                  else nvl(T.TRADE_AMT,0) end RVALUE,T.FINPROD_ID
                  FROM TRD_PRODUCT_DEAL T
                 INNER JOIN TRD_PRODUCT_DEAL_ADD T1 ON T.trade_id = T1.trade_id
                INNER JOIN FIN_PRODUCT_TYPE T3 ON T.FINPROD_ID = T3.FINPROD_ID
                 INNER JOIN FIN_PRODUCT T2 on T.FINPROD_ID = T2.FINPROD_ID
                 WHERE 
                    T.PS  IN (''T04'',''T06'')
                   AND (T3.TYPE_8 IN (''F04'') OR (T3.TYPE_8 = ''F02'' and T2.TRADE_MARKET = ''09'' and T3.TYPE_6=''F02''))
                   AND T.TRADE_STATUS = ''01''
                   AND T.IS_CANCEL = ''N''
                   AND T.TRADE_DATE <=DATE''${valDate}''
                  AND T1.PORTFOLIO_ID IN ${portfolioCode}
                   AND NOT EXISTS (
                      -- 没有后续申购确认交易
                      SELECT 1 FROM TRD_PRODUCT_DEAL TRD WHERE T.TRADE_ID = TRD.B_TRADE_ID AND TRD.TRADE_STATUS = ''01'' AND TRD.IS_CANCEL = ''N''   
                )
) targetData         
      INNER JOIN PROD N ON targetData.FINPROD_ID = N.FINPROD_ID         
      WHERE N.FINPROD_ID NOT IN (SELECT FINPROD_ID FROM FDLVBOND UNION ALL SELECT FINPROD_ID FROM AABOND)
        AND N.CDATE <= DATE ''${valDate}''';

