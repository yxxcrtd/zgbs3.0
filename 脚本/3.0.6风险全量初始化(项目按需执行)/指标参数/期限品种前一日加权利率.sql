(SELECT t1.INT_RATE_ID ,t1.INT_RATE,rank() over (partition by t1.INT_RATE_ID order by t1.EFF_DATE desc) rk
 FROM MST_INT_RATE_INFO t1
 WHERE  t1.EFF_DATE<=DATE''${valDate}''
)where rk=1)N
on M.TERM_TYPE = N.INT_RATE_ID';

