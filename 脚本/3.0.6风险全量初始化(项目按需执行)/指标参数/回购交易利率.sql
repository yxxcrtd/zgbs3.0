DECLARE
----实时、买入预占、卖出预占
V_CONTENT_01_02_03 CLOB := 'select A.FINPROD_ID AS RKEY, case WHEN A.TRADE_MARKET !=''01'' THEN B.TERM_TYPE ELSE ''D''||B.TERM_TYPE END AS RVALUE
from TRD_PRODUCT_DEAL  A
inner join TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
inner join FIN_TRADE_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
where A.FINPROD_TYPE2 in (''F02'',''F03'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''';

----事后(日间)
V_CONTENT_04 CLOB := 'select B.TERM_TYPE ||'',''||A.TRADE_ID AS RKEY,B.INT_RATE AS RVALUE
from TRD_PRODUCT_DEAL  A
inner join TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and NVL(A.IS_CANCEL,''N'') =''N''
inner join FIN_TRADE_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
where A.FINPROD_TYPE2 in (''F02'',''F03'')
AND A.PS IN (''T01'',''T02'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''
union all
select B.TERM_TYPE ||'',''||A.TRADE_ID AS RKEY,B.INT_RATE AS RVALUE
from TRD_PRODUCT_TEMP_DEAL  A
inner join TRD_PRODUCT_TEMP_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS =''01''
and NVL(A.IS_CANCEL,''N'') =''N''
inner join FIN_TRADE_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
where A.FINPROD_TYPE2 in (''F02'',''F03'')
AND A.PS IN (''T01'',''T02'',''03'',''04'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''
union all
select  B.TERM_TYPE ||'',''||A.TRADE_ID AS RKEY,B.INT_RATE AS RVALUE
from WFL_TRD_PRODUCT_DEAL  A
inner join WFL_TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS=''01''
and substr(A.TRADE_ID,length(A.TRADE_ID),length(A.TRADE_ID)-1)!=''R''
inner join FIN_TRADE_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
INNER JOIN SYS_WFL_BUSINESS_LIST swbl on A.WORKFLOW_ID = swbl.SEQ_NO and swbl.PROCESS_STATE != ''BACK''
where A.FINPROD_TYPE2 in (''F02'',''F03'')
AND A.PS IN (''T01'',''T02'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''';

----事后(日终)
V_CONTENT_05 CLOB := 'select  B.TERM_TYPE ||'',''||A.TRADE_ID AS RKEY,B.INT_RATE AS RVALUE
from TRD_PRODUCT_DEAL  A
inner join TRD_PRODUCT_DEAL_ADD C
on A.TRADE_ID=C.TRADE_ID
and A.TRADE_STATUS !=''03''
and NVL(A.IS_CANCEL,''N'') =''N''
inner join FIN_TRADE_PRODUCT B
on A.FINPROD_ID = B.FINPROD_ID
where A.FINPROD_TYPE2 in (''F02'',''F03'')
AND A.PS IN (''T01'',''T02'')
and C.PORTFOLIO_ID IN ${portfolioCode}
and A.TRADE_DATE = DATE''${valDate}''';

