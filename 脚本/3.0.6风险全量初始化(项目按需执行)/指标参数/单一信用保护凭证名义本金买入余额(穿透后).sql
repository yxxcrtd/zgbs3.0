V_CONTENT_01_02_03 CLOB := 'SELECT SUM(NVL(PSP.SHARE_AMT, 0)) RVALUE, PSP.PORTFOLIO_ID || '','' || PSP.FINPROD_ID RKEY
FROM PTL_SEC_PIERCE_VALUTION PSP
INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = PSP.FINPROD_ID AND FP.FINPROD_TYPE2 = ''F37''
WHERE PSP.CDATE = DATE ''${valDate}'' - 1
GROUP BY PSP.PORTFOLIO_ID,PSP.FINPROD_ID';

----事后(日间)
V_CONTENT_04 CLOB := 'SELECT SUM(NVL(AMT.TRADE_AMT, 0)) RVALUE,
       AMT.FINPROD_ID             RKEY,
       AMT.FINPROD_ABBR           RKEYCN
FROM (
         SELECT SUM(NVL(PSP.SHARE_AMT, 0)) TRADE_AMT, PSP.FINPROD_ID, FP.FINPROD_ABBR
         FROM PTL_SEC_PIERCE_VALUTION PSP
                  INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = PSP.FINPROD_ID AND FP.FINPROD_TYPE2 = ''F37''
         WHERE PSP.CDATE = DATE ''${valDate}'' - 1 AND PSP.PORTFOLIO_ID IN ${portfolioCode}
         GROUP BY PSP.FINPROD_ID, FP.FINPROD_ABBR
         UNION ALL
         SELECT nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T07'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))),
                          0) AS TRADE_AMT,
                n.FINPROD_ID,
                FP.FINPROD_ABBR
         FROM TRD_PRODUCT_DEAL_ADD m
                  INNER JOIN TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID
                  INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
         WHERE m.PORTFOLIO_ID IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
           AND FP.FINPROD_TYPE2 = ''F37''
           AND n.PS IN (''T01'', ''T02'', ''T04'', ''T07'')
         GROUP BY n.FINPROD_ID, FP.FINPROD_ABBR
         UNION ALL
         SELECT nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T07'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))),
                          0) AS TRADE_AMT,
                n.FINPROD_ID,
                FP.FINPROD_ABBR
         FROM TRD_PRODUCT_TEMP_DEAL_ADD m
                  INNER JOIN TRD_PRODUCT_TEMP_DEAL n ON m.TRADE_ID = n.TRADE_ID
                  INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
         WHERE m.PORTFOLIO_ID IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
           AND FP.FINPROD_TYPE2 = ''F37''
           AND n.PS IN (''T01'', ''T02'', ''T04'', ''T07'')
         GROUP BY n.FINPROD_ID, FP.FINPROD_ABBR
         UNION ALL
         SELECT nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    + nvl(sum(decode(n.PS, ''T04'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))), 0)
                    - nvl(sum(decode(n.PS, ''T07'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT * -1, n.TRADE_AMT))),
                          0) AS TRADE_AMT,
                n.FINPROD_ID,
                FP.FINPROD_ABBR
         FROM WFL_TRD_PRODUCT_DEAL_ADD m
                  INNER JOIN WFL_TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID
                  INNER JOIN FIN_PRODUCT FP ON FP.FINPROD_ID = n.FINPROD_ID
         WHERE m.PORTFOLIO_ID IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
           AND FP.FINPROD_TYPE2 = ''F37''
           AND n.PS IN (''T01'', ''T02'', ''T04'', ''T07'')
         GROUP BY n.FINPROD_ID, FP.FINPROD_ABBR
     ) AMT
GROUP BY AMT.FINPROD_ID, AMT.FINPROD_ABBR';

