    WHERE FP.FINPROD_TYPE2 IN（ ''F01'',''F32'') AND FPT.type_6 IN (''B03'',''B04'') AND FP.IS_RIGHT = ''N''
  UNION ALL
    -- 央票、同业存单（含权）
    SELECT FP.FINPROD_ID,
    CASE WHEN NVL(FXZ.MDATE, t1.MDATE) < t1.MDATE THEN NVL(FXZ.MDATE,FP.MDATE) ELSE NVL(t1.MDATE,FP.MDATE) END MDATE,FP.FINPROD_NAME
    FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    AND FP.FINPROD_TYPE2 IN（ ''F01'',''F32'') AND FPT.type_6 IN (''B03'',''B04'')
    LEFT JOIN (
        SELECT FCP.FINPROD_ID,FCP.MDATE FROM FIN_CASH_PLAN FCP
        WHERE FCP.FINPROD_TYPE2 IN（ ''F01'',''F32'') AND FCP.CASH_TYPE = ''04'' AND FCP.CASH_ID IN (
            SELECT FCI.CASH_ID FROM FIN_CASH_INFO FCI
            INNER JOIN FIN_CASH_CALC_RULE FCC ON FCC.CASH_ID = FCI.CASH_ID AND FCC.CALC_TYPE = ''02''
            WHERE FCI.CASH_TYPE_1 = ''02''
        )
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN (
        SELECT FINPROD_ID,min(EXERCISE_DATE) MDATE FROM FIN_EXERCISE_PLAN
        WHERE EXERCISE_DATE >= DATE ''${valDate}''
        GROUP BY FINPROD_ID
    ) t1 ON t1.FINPROD_ID = FP.FINPROD_ID
    WHERE FP.IS_RIGHT = ''Y''
)
SELECT TO_NUMBER(target.MDATE - DATE ''${valDate}'') RVALUE, target.FINPROD_ID RKEY, target.FINPROD_NAME RKEYCN
FROM (
        
        select sum(tmp.SHARE_AMT) AMOUNT,tmp.FINPROD_ID,tmp.MDATE,tmp.FINPROD_NAME from 
        (
                SELECT SUM(NVL(PSP.SHARE_AMT,0)) SHARE_AMT, PSP.FINPROD_ID FINPROD_ID, ASSET.MDATE MDATE, ASSET.FINPROD_NAME FINPROD_NAME
                FROM PTL_SEC_VALUTION PSP
                INNER JOIN ASSET ON ASSET.FINPROD_ID = PSP.FINPROD_ID
                WHERE ASSET.MDATE > DATE ''${valDate}''
                AND PSP.PORTFOLIO_ID IN ${portfolioCode} AND PSP.CDATE = DATE ''${valDate}''
                GROUP BY PSP.FINPROD_ID, ASSET.MDATE, ASSET.FINPROD_NAME
                UNION ALL
                      ---银行间质押式回购
                    select  SUM(NVL(t.PRIN_AMT,0)) SHARE_AMT, t.FINPROD_ID FINPROD_ID, t.MDATE MDATE, t.TRADE_ID  FINPROD_NAME  from TRD_PRODUCT_DEAL  t 
                    left join TRD_BANK_MANUAL_SETTLE_INFO js on t.FINPROD_ID = js.FINPROD_ID 
                    where  t.FINPROD_TYPE2 IN (''F03'') and t.TRADE_STATUS=''01'' and t.IS_CANCEL=''N'' and t.TRADE_MARKET=''01'' and t.ps=''T01''and (js.SETTLE_SEQ_NO is null and t.MDATE >  date''${valDate}'')
                      GROUP BY t.FINPROD_ID, t.MDATE, t.TRADE_ID
                UNION ALL
                  ---场内回购回购没有到期交易
                  select SUM(NVL(t.PRIN_AMT,0)) SHARE_AMT, t.FINPROD_ID FINPROD_ID, t.MDATE MDATE, t.TRADE_ID  FINPROD_NAME from TRD_PRODUCT_DEAL t 
                  left join TRD_PRODUCT_DEAL dq on t.FINPROD_ID= dq.FINPROD_ID and dq.ps IN (''T07'',''T22'',''T23'') 
                  where t.FINPROD_TYPE2 IN (''F03'',''F05'') and t.TRADE_STATUS=''01'' and t.IS_CANCEL=''N'' and t.ps=''T01'' and t.TRADE_MARKET IN (''03'',''04'')
                   and (dq.TRADE_ID is null  and t.MDATE > date''${valDate}'')
                    GROUP BY t.FINPROD_ID, t.MDATE, t.TRADE_ID
                UNION ALL
                    --银行间买断式回购
                      select SUM(NVL(t.PRIN_AMT,0)) SHARE_AMT, t.FINPROD_ID FINPROD_ID, t.MDATE MDATE, t.TRADE_ID FINPROD_NAME from TRD_PRODUCT_DEAL t 
                  left join TRD_PRODUCT_DEAL dq on t.FINPROD_ID= dq.FINPROD_ID and dq.ps IN (''T07'',''T22'',''T23'') 
                  where t.FINPROD_TYPE2 IN (''F05'') and t.TRADE_STATUS=''01'' and t.IS_CANCEL=''N'' and t.ps=''T01'' and t.TRADE_MARKET IN (''01'') 
                   and (dq.TRADE_ID is null  and t.MDATE > DATE''${valDate}'')
                    GROUP BY t.FINPROD_ID, t.MDATE, t.TRADE_ID
        )tmp
        group by  tmp.FINPROD_ID, tmp.MDATE, tmp.FINPROD_NAME
) target
        WHERE target.AMOUNT > 0';

