)

SELECT RKEY, RVALUE, RKEYCN FROM (

SELECT SUM(NVL(SHARE_AMT,0)) SHARE_AMT, RKEY, MDATE RVALUE, FINPROD_NAME RKEYCN FROM (

    SELECT SUM(NVL(PSP.AMOUNT,0)) SHARE_AMT, TEMP2.FINPROD_ID RKEY, TEMP2.MDATE, FP.FINPROD_NAME

