     SELECT DISTINCT ORG_NO, COR_ORGID
     FROM (
              SELECT ORG_NO, COR_ORGID FROM INF_ORG_CORRELATION
              UNION ALL
              SELECT COR_ORGID ORG_NO, ORG_NO COR_ORGID FROM INF_ORG_CORRELATION
          )  REL
 ),
 ORG_REL_RESULT AS (
     SELECT FINPROD_ID, ORG_CODE, ORG_CODE ORG_CODE_UNION FROM TEMP WHERE ORG_CODE IN  ${issuerCode}
     UNION ALL
     SELECT DISTINCT C.FINPROD_ID, A.ORG_CODE, B.COR_ORGID ORG_CODE_UNION FROM TEMP A
