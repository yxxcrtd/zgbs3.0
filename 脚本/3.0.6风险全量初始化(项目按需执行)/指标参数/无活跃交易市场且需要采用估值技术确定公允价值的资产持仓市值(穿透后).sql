V_CONTENT_01_02_03 CLOB := 'WITH PROD AS (
	-- 项目类
    SELECT FPT.FINPROD_ID FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    WHERE FPT.TYPE_8 =''F06''
  UNION
    -- 存款（不含活期存款）
    SELECT FPT.FINPROD_ID FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = FP.FINPROD_ID
    WHERE FP.FINPROD_TYPE2 = ''F07'' AND FPT.TYPE_6 != ''D03''
   UNION
   -- 是否无活跃交易市场且需要采用估值技术确定公允价值资产
    SELECT FPT.FINPROD_ID FROM FIN_PRODUCT_TYPE FPT
    WHERE EXISTS (
        SELECT 1 FROM RSK_SPECIFIC_ASSET_TYPE RSAT WHERE RSAT.IS_LIQUIDITY1 = ''Y'' AND (
        (REGEXP_INSTR(RSAT.TYPE_1||''_''||RSAT.TYPE_2||''_''||RSAT.TYPE_3||''_''||RSAT.TYPE_4 ,
            FPT.TYPE_9||''_''||FPT.TYPE_10||''_''||FPT.TYPE_11||''_''||FPT.TYPE_12) >= 1 AND RSAT.FINPROD_ID IS NULL)
        OR FPT.FINPROD_ID = RSAT.FINPROD_ID)
    )
)

SELECT NVL(SUM(RVALUE),0) RVALUE,RKEY FROM (
SELECT
    NVL(SUM(NVL(m.MARKET_VALUE,0)+nvl(m.TDY_INTINCEXP, 0)),0) RVALUE,
    M.PORTFOLIO_ID RKEY
FROM PTL_SEC_PIERCE_VALUTION M
INNER JOIN PROD N ON M.FINPROD_ID = N.FINPROD_ID
WHERE M.CDATE = date''${valDate}'' - 1 GROUP BY M.PORTFOLIO_ID
) GROUP BY RKEY';

