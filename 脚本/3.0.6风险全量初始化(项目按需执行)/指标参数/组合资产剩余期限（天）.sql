V_CONTENT_01_02_03 CLOB := 'WITH ASSET AS (
   -- 逆回购、F09-拆出、、F30-融出
    SELECT FINPROD_ID,TO_NUMBER(MDATE - DATE''${valDate}'') LAST_PERIOD FROM FIN_TRADE_PRODUCT
    WHERE FINPROD_TYPE2 IN (''F03'',''F05'',''F09'',''F30'')
    UNION -- 股票
    SELECT FP.FINPROD_ID,1 LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F11''
    UNION -- 活期存款
    SELECT FP.FINPROD_ID,0 LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F05'' AND FPT.TYPE_6 = ''D03''
    UNION  -- 非活期存款
    SELECT FP.FINPROD_ID,TO_NUMBER(FP.MDATE - DATE''${valDate}'') LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F05'' AND FPT.TYPE_6 != ''D03''
    UNION -- 债券（非含权）
    SELECT FP.FINPROD_ID,  -- 贴现、零息、利随本清
    CASE WHEN FP.COUPON_SPECIES IN (''02'',''03'',''04'') THEN TO_NUMBER(FP.MDATE - DATE''${valDate}'')
    ELSE TO_NUMBER(NVL(FXZ.MDATE, FP.MDATE) - DATE''${valDate}'') END LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    LEFT JOIN (
        SELECT FCC.FINPROD_ID,min(FCC.EFF_DATE) MDATE FROM FIN_CASH_CALC_RULE FCC
        INNER JOIN FIN_PRODUCT t2 ON FCC.FINPROD_ID = t2.FINPROD_ID
        LEFT JOIN FIN_CASH_INFO T5 ON T5.FINPROD_ID = FCC.FINPROD_ID AND T5.CASH_TYPE_2 = ''C02''
        LEFT JOIN FIN_RATE_INFO T6 ON T6.CASH_ID = T5.CASH_ID AND T6.EFF_DATE = t2.VDATE
        WHERE FCC.EFF_DATE > DATE''${valDate}''
        GROUP BY FCC.FINPROD_ID
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID
    WHERE FPT.TYPE_8 IN (''F01'',''F17'') AND FP.IS_RIGHT = ''N''
    UNION  -- 债券（含权）
    SELECT FP.FINPROD_ID,  -- 贴现、零息、利随本清
    CASE WHEN FP.COUPON_SPECIES IN (''02'',''03'',''04'') THEN TO_NUMBER(FP.MDATE - DATE''${valDate}'')
    WHEN NVL(FXZ.MDATE, t1.MDATE) < t1.MDATE THEN TO_NUMBER(NVL(FXZ.MDATE,FP.MDATE) - DATE''${valDate}'')
    ELSE TO_NUMBER(NVL(t1.MDATE,FP.MDATE) - DATE''${valDate}'') END LAST_PERIOD
    FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    AND FPT.TYPE_8 IN (''F01'',''F17'')
    LEFT JOIN (
        SELECT FCC.FINPROD_ID,min(FCC.EFF_DATE) MDATE FROM FIN_CASH_CALC_RULE FCC
        INNER JOIN FIN_PRODUCT t2 ON FCC.FINPROD_ID = t2.FINPROD_ID
        LEFT JOIN FIN_CASH_INFO T5 ON T5.FINPROD_ID = FCC.FINPROD_ID AND T5.CASH_TYPE_2 = ''C02''
        LEFT JOIN FIN_RATE_INFO T6 ON T6.CASH_ID = T5.CASH_ID
        AND T6.EFF_DATE = t2.VDATE
        WHERE FCC.EFF_DATE > DATE''${valDate}''
        GROUP BY FCC.FINPROD_ID
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID
    LEFT JOIN (
        SELECT FINPROD_ID,min(EXERCISE_DATE) MDATE FROM FIN_EXERCISE_PLAN
        WHERE EXERCISE_DATE > DATE''${valDate}''
        GROUP BY FINPROD_ID
    ) t1 ON t1.FINPROD_ID = FP.FINPROD_ID
    WHERE FP.IS_RIGHT = ''Y''
    UNION -- 非标债权
    SELECT FP.FINPROD_ID,  -- 下一个利率调整日-计算日
    TO_NUMBER(NVL(FXZ.MDATE, FP.MDATE) - DATE''${valDate}'') LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    LEFT JOIN (
        SELECT FCC.FINPROD_ID,min(FCC.EFF_DATE) MDATE FROM FIN_CASH_CALC_RULE FCC
        INNER JOIN FIN_PRODUCT t2 ON FCC.FINPROD_ID = t2.FINPROD_ID
        LEFT JOIN FIN_CASH_INFO T5 ON T5.FINPROD_ID = FCC.FINPROD_ID AND T5.CASH_TYPE_2 = ''C02''
        LEFT JOIN FIN_RATE_INFO T6 ON T6.CASH_ID = T5.CASH_ID
        AND T6.EFF_DATE = t2.VDATE
        WHERE FCC.EFF_DATE > DATE''${valDate}''
        GROUP BY FCC.FINPROD_ID
    ) FXZ ON FXZ.FINPROD_ID = FP.FINPROD_ID WHERE FPT.TYPE_8 = ''F06''
    UNION  -- 计划类利率型\计划类净值型\计划类货币型
    SELECT FP.FINPROD_ID,1 LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 IN (''F03'',''F04'',''F09'')
    UNION -- 基金
    SELECT FP.FINPROD_ID, DECODE(PLAN.MDATE, NULL, 1, TO_NUMBER(PLAN.MDATE - DATE''${valDate}'')) LAST_PERIOD
    FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    LEFT JOIN (  -- 下一个开放赎回起始日
        SELECT min(FOP.OPEN_DATE_STR) MDATE, FOP.FINPROD_ID FROM FIN_OPEN_PLAN FOP
        INNER JOIN FIN_PRODUCT_TYPE FPT ON FOP.FINPROD_ID = FPT.FINPROD_ID
        WHERE OPEN_DATE_STR > DATE''${valDate}'' AND FPT.TYPE_8 = ''F02''
        AND OPEN_TYPE IN (''02'',''03'')
        GROUP BY FOP.FINPROD_ID
    ) PLAN ON PLAN.FINPROD_ID = FP.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F02''
    UNION -- 其他资产
    SELECT FP.FINPROD_ID,TO_NUMBER(FP.MDATE - DATE''${valDate}'') LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 NOT IN (''F01'',''F02'',''F04'',''F03'',''F05'',''F06'',''F09'',''F17'')
) SELECT FINPROD_ID RKEY,  NVl(LAST_PERIOD,0) RVALUE FROM ASSET';

