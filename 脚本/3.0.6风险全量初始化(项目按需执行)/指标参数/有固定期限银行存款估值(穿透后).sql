DECLARE
----实时、买入预占、卖出预占
V_CONTENT_01_02_03 CLOB := 'SELECT
    NVL(SUM(NVL(VAL.MARKET_VALUE,0)+nvl(VAL.TDY_INTINCEXP, 0)),0) RVALUE,
    VAL.PORTFOLIO_ID RKEY
FROM PTL_SEC_PIERCE_VALUTION VAL
INNER JOIN FIN_PRODUCT PRD ON VAL.FINPROD_ID = PRD.FINPROD_ID
INNER JOIN FIN_PRODUCT_ADD FPA ON FPA.FINPROD_ID = PRD.FINPROD_ID
INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = PRD.FINPROD_ID
INNER JOIN PA_FIN_PRODUCT PFP ON PFP.FINPROD_ID = PRD.FINPROD_ID
WHERE VAL.CDATE = date''${valDate}'' - 1 AND PRD.FINPROD_TYPE2 = ''F07''
-- 这里是是否可提前支取的条件
AND (FPA.IS_INADVANCE IS NULL OR FPA.IS_INADVANCE = ''01'')
AND PRD.MDATE IS NOT NULL AND FPT.TYPE_6 != ''D03''
GROUP BY VAL.PORTFOLIO_ID';

----事后(日间)
V_CONTENT_04 CLOB := 'SELECT SUM(TRADE_AMT) as RVALUE FROM (
    SELECT
        NVL(SUM(NVL(VAL.MARKET_VALUE ,0) + NVL(TDY_INTINCEXP,0)),0) TRADE_AMT
    FROM PTL_SEC_PIERCE_VALUTION VAL
    INNER JOIN FIN_PRODUCT PRD ON VAL.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_ADD FPA ON FPA.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN PA_FIN_PRODUCT PFP ON PFP.FINPROD_ID = PRD.FINPROD_ID
    WHERE VAL.CDATE = date''${valDate}'' - 1 AND VAL.PORTFOLIO_ID IN ${portfolioCode}
    -- 是否可提前支取条件
    AND (FPA.IS_INADVANCE IS NULL OR FPA.IS_INADVANCE = ''01'')
    AND PRD.FINPROD_TYPE2 = ''F07'' AND PRD.MDATE IS NOT NULL AND FPT.TYPE_6 != ''D03''
  UNION ALL
    SELECT
        nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T22'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T23'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T25'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T26'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T38'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0) AS TRADE_AMT
    FROM TRD_PRODUCT_DEAL_ADD m
    INNER JOIN TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID
    INNER JOIN FIN_PRODUCT PRD ON n.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_ADD FPA ON FPA.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN PA_FIN_PRODUCT PFP ON PFP.FINPROD_ID = PRD.FINPROD_ID
    WHERE m.PORTFOLIO_ID IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
    -- 是否可提前支取条件
    AND (FPA.IS_INADVANCE IS NULL OR FPA.IS_INADVANCE = ''01'')
    AND PRD.FINPROD_TYPE2 = ''F07'' AND PRD.MDATE IS NOT NULL AND FPT.TYPE_6 != ''D03''
    AND n.PS IN (''T01'', ''T02'', ''T22'', ''T23'', ''T25'', ''T26'',''T38'')
  UNION ALL
    SELECT
        nvl(sum(decode(n.PS, ''T01'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T22'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T23'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      + nvl(sum(decode(n.PS, ''T25'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T26'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0)
      - nvl(sum(decode(n.PS, ''T38'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0) AS TRADE_AMT
    FROM WFL_TRD_PRODUCT_DEAL_ADD m
    INNER JOIN WFL_TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID AND n.TRADE_STATUS != ''03''
  INNER JOIN SYS_WFL_BUSINESS_LIST swbl on n.WORKFLOW_ID = swbl.SEQ_NO and swbl.PROCESS_STATE != ''BACK''
    INNER JOIN FIN_PRODUCT PRD ON n.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_ADD FPA ON FPA.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN PA_FIN_PRODUCT PFP ON PFP.FINPROD_ID = PRD.FINPROD_ID
    WHERE m.PORTFOLIO_ID IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
    -- 是否可提前支取条件
    AND (FPA.IS_INADVANCE IS NULL OR FPA.IS_INADVANCE = ''01'')
    AND PRD.FINPROD_TYPE2 = ''F07'' AND PRD.MDATE IS NOT NULL AND FPT.TYPE_6 != ''D03''
    AND n.PS IN (''T01'', ''T02'', ''T22'', ''T23'', ''T25'', ''T26'',''T38'')
  UNION ALL
    SELECT
       nvl(sum(decode(n.PS, ''T02'', decode(TRADE_STATUS, ''03'', n.TRADE_AMT*-1, n.TRADE_AMT))), 0) AS TRADE_AMT
    FROM WFL_TRD_PRODUCT_DEAL_ADD m
    INNER JOIN WFL_TRD_PRODUCT_DEAL n ON m.TRADE_ID = n.TRADE_ID AND n.TRADE_STATUS != ''03''
  INNER JOIN SYS_WFL_BUSINESS_LIST swbl on n.WORKFLOW_ID = swbl.SEQ_NO and swbl.PROCESS_STATE != ''BACK''
    INNER JOIN FIN_PRODUCT PRD ON n.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_ADD FPA ON FPA.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FPT.FINPROD_ID = PRD.FINPROD_ID
    INNER JOIN PA_FIN_PRODUCT PFP ON PFP.FINPROD_ID = PRD.FINPROD_ID
    WHERE n.counter_id IN ${portfolioCode} AND n.TRADE_DATE = DATE''${valDate}''
    -- 是否可提前支取条件
    AND (FPA.IS_INADVANCE IS NULL OR FPA.IS_INADVANCE = ''01'')
    AND PRD.FINPROD_TYPE2 = ''F07'' AND PRD.MDATE IS NOT NULL AND FPT.TYPE_6 != ''D03''
    AND n.PS = ''T02''
    AND EXISTS (SELECT 1 FROM SYS_PARA WHERE PARA_CODE = ''is_auto_generate_negate_deal'' AND PARAM_VALUE = ''Y'')
)';

