DECLARE
---- 实时、买入预占、卖出预占
V_CONTENT_01_02_03 CLOB := 'WITH ASSET AS (
    -- 逆回购交易
    SELECT FINPROD_ID,TO_NUMBER(MDATE - DATE ''${valDate}'') LAST_PERIOD FROM FIN_TRADE_PRODUCT
    WHERE FINPROD_TYPE2 IN (''F03'',''F05'') and MDATE>=DATE ''${valDate}''
  UNION
    --拆借交易
    SELECT FINPROD_ID,TO_NUMBER(MDATE - DATE ''${valDate}'') LAST_PERIOD FROM FIN_TRADE_PRODUCT
    WHERE FINPROD_TYPE2 IN (''F09'')
  UNION
    -- 活期存款
    SELECT FP.FINPROD_ID,0 LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F05'' AND FPT.TYPE_6 = ''D03''
  UNION
    -- 非活期存款
    SELECT FP.FINPROD_ID,TO_NUMBER(FP.MDATE - DATE ''${valDate}'') LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F05'' AND FPT.TYPE_6 != ''D03''
  UNION
    -- 计划类净值型、计划类利率型
    SELECT FP.FINPROD_ID,1 LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 IN (''F04'',''F09'')
  UNION
    -- 基金
    SELECT FP.FINPROD_ID, DECODE(PLAN.MDATE, NULL, 1, TO_NUMBER(PLAN.MDATE - DATE ''${valDate}'')) LAST_PERIOD
    FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    LEFT JOIN (
        -- 下一个开放赎回起始日
        SELECT min(FOP.OPEN_DATE_STR) MDATE, FOP.FINPROD_ID FROM FIN_OPEN_PLAN FOP
        INNER JOIN FIN_PRODUCT_TYPE FPT ON FOP.FINPROD_ID = FPT.FINPROD_ID
        WHERE OPEN_DATE_STR > DATE ''${valDate}'' AND FPT.TYPE_8 = ''F02''
        AND OPEN_TYPE IN (''02'',''03'')
        GROUP BY FOP.FINPROD_ID
    ) PLAN ON PLAN.FINPROD_ID = FP.FINPROD_ID
    WHERE FPT.TYPE_8 = ''F02''
  UNION
    -- 其他资产
    SELECT FP.FINPROD_ID,TO_NUMBER(FP.MDATE - DATE ''${valDate}'') LAST_PERIOD FROM FIN_PRODUCT FP
    INNER JOIN FIN_PRODUCT_TYPE FPT ON FP.FINPROD_ID = FPT.FINPROD_ID
    WHERE FPT.TYPE_8 NOT IN (''F02'',''F05'',''F04'',''F09'')
) SELECT FINPROD_ID RKEY,  NVl(LAST_PERIOD,0) RVALUE FROM ASSET';

BEGIN
    UPDATE RSK_ISUP_INDICATOR_PARA_DTL SET CONTENT = V_CONTENT_01_02_03 WHERE PARA_CODE = 'ZCSYCXQXDAY' and PARA_GRANULARITY in('01','02','03');
END;
