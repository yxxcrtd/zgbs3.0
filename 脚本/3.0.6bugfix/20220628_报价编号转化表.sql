--报价编号转化表
drop table QUOTE_ID_CONVER;
CREATE TABLE QUOTE_ID_CONVER
    (
        QUOTE_DATE DATE NOT NULL,
        QUOTE_ID VARCHAR2(50) NOT NULL,
        CL_ORD_ID VARCHAR2(50) NOT NULL, 
        CREATE_USER VARCHAR2(20),
        CREATE_TIME TIMESTAMP(6),
        UPDATE_USER VARCHAR2(20),
        UPDATE_TIME TIMESTAMP(6)
    );
COMMENT ON TABLE QUOTE_ID_CONVER
IS
    '报价编号转化表';
COMMENT ON COLUMN QUOTE_ID_CONVER.QUOTE_DATE
IS
    '报价日期';
COMMENT ON COLUMN QUOTE_ID_CONVER.QUOTE_ID
IS
    '报价编号';
COMMENT ON COLUMN QUOTE_ID_CONVER.CL_ORD_ID
IS
    '客户参考编号';  
COMMENT ON COLUMN QUOTE_ID_CONVER.CREATE_USER
IS
    '创建人';
COMMENT ON COLUMN QUOTE_ID_CONVER.CREATE_TIME
IS
    '创建时间';
COMMENT ON COLUMN QUOTE_ID_CONVER.UPDATE_USER
IS
    '更新人';
COMMENT ON COLUMN QUOTE_ID_CONVER.UPDATE_TIME
IS
    '更新时间';



