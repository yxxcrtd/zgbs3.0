DROP TABLE "T_APPOINT_INSTRUCTION_RECORD";
CREATE TABLE "T_APPOINT_INSTRUCTION_RECORD"
(
    "ID"           VARCHAR2(32)   NOT NULL,
    "ENTRUST_ID"   VARCHAR2(64)   NOT NULL,
    "ENTRUST_INFO" VARCHAR2(4000) NOT NULL,
    "DETAIL_INFO"  VARCHAR2(4000) NOT NULL,
    "PLEDGE_INFO"  VARCHAR2(4000),
    "STATUS"       NUMBER         NOT NULL,
    "CHECK_MSG"    VARCHAR2(255),
    "REMARK"       VARCHAR2(255),
    PRIMARY KEY ("ID")
);

COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."ID" IS '主键';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."ENTRUST_ID" IS '指令编号';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."ENTRUST_INFO" IS '指令信息';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."DETAIL_INFO" IS '组合信息';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."PLEDGE_INFO" IS '质押券信息';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."STATUS" IS '状态：0-新建，1-检查通过，2-检查不通过';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."CHECK_MSG" IS '检查结果描述';
COMMENT ON COLUMN "T_APPOINT_INSTRUCTION_RECORD"."REMARK" IS '备注';
