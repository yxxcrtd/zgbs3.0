DROP TABLE "T_RECORD_LOG";
CREATE TABLE "T_RECORD_LOG"
(
    "ID"           VARCHAR2(32)   NOT NULL,
    "BUSI_CODE1"   VARCHAR2(64)   NOT NULL,
    "BUSI_CODE2"   VARCHAR2(64),
    "BUSI_CODE3"   VARCHAR2(64),
    "RECORD_INFO"  VARCHAR2(4000) NOT NULL,
    "DETAIL_INFO"  VARCHAR2(4000),
    "PLEDGE_INFO"  VARCHAR2(4000),
    "LOG_TYPE"     NUMBER         NOT NULL,
    "STATUS"       NUMBER         NOT NULL,
    "CHECK_MSG"    VARCHAR2(255),
    "REMARK"       VARCHAR2(255),
    "CREATE_USER"  VARCHAR2(32),
    "CREATE_TIME"  TIMESTAMP      NOT NULL,
    "UPDATE_USER"  VARCHAR2(32),
    "UPDATE_TIME"  TIMESTAMP      NOT NULL,
    PRIMARY KEY ("ID")
);

COMMENT ON TABLE "T_RECORD_LOG" IS '记录日志表';

COMMENT ON COLUMN "T_RECORD_LOG"."ID" IS '主键';
COMMENT ON COLUMN "T_RECORD_LOG"."BUSI_CODE1" IS '业务编号1';
COMMENT ON COLUMN "T_RECORD_LOG"."BUSI_CODE2" IS '业务编号2';
COMMENT ON COLUMN "T_RECORD_LOG"."BUSI_CODE3" IS '业务编号3';
COMMENT ON COLUMN "T_RECORD_LOG"."RECORD_INFO" IS '记录信息';
COMMENT ON COLUMN "T_RECORD_LOG"."DETAIL_INFO" IS '组合信息';
COMMENT ON COLUMN "T_RECORD_LOG"."PLEDGE_INFO" IS '质押券信息';
COMMENT ON COLUMN "T_RECORD_LOG"."LOG_TYPE" IS '类型：0-指令分发，1-成交，2-手动交收，3-执行进度';
COMMENT ON COLUMN "T_RECORD_LOG"."STATUS" IS '状态：0-新建，1-检查通过，2-检查不通过';
COMMENT ON COLUMN "T_RECORD_LOG"."CHECK_MSG" IS '检查结果描述';
COMMENT ON COLUMN "T_RECORD_LOG"."REMARK" IS '备注';
COMMENT ON COLUMN "T_RECORD_LOG"."CREATE_USER" IS '创建人';
COMMENT ON COLUMN "T_RECORD_LOG"."CREATE_TIME" IS '创建时间';
COMMENT ON COLUMN "T_RECORD_LOG"."UPDATE_USER" IS '修改人';
COMMENT ON COLUMN "T_RECORD_LOG"."UPDATE_TIME" IS '修改时间';
