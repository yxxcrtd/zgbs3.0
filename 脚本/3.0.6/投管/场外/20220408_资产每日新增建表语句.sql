-- 资产每日信息建表语句
 drop table ASSET_DAILY_INFO;
CREATE TABLE
    ASSET_DAILY_INFO
    ( 
        FINPROD_ID VARCHAR2(50) NOT NULL, 
        CDATE DATE NOT NULL,
        M_PENDING_PERIOD NUMBER(30,14),
        M_PENDING_PERIOD_UNIT VARCHAR2(32),
        EX_PENDING_PERIOD NUMBER(30,14),
        EX_PENDING_PERIOD_UNIT VARCHAR2(32),
        CREATE_USER VARCHAR2(20) NOT NULL,
        CREATE_DEPT VARCHAR2(32),
        CREATE_TIME TIMESTAMP(6) NOT NULL,
        UPDATE_USER VARCHAR2(20) NOT NULL,
        UPDATE_TIME TIMESTAMP(6) NOT NULL, 
        CONSTRAINT PK_ASSET_DAILY_INFO PRIMARY KEY (FINPROD_ID, CDATE)
    );
COMMENT ON TABLE ASSET_DAILY_INFO
IS
    '资产每日信息'; 
COMMENT ON COLUMN ASSET_DAILY_INFO.FINPROD_ID
IS
    '金融产品代码'; 
COMMENT ON COLUMN ASSET_DAILY_INFO.CDATE
IS
    '日期'; 
COMMENT ON COLUMN ASSET_DAILY_INFO.M_PENDING_PERIOD
IS
    '到期日待偿期';
COMMENT ON COLUMN ASSET_DAILY_INFO.M_PENDING_PERIOD_UNIT
IS
    '到期日待偿期单位（D/Y）';
COMMENT ON COLUMN ASSET_DAILY_INFO.EX_PENDING_PERIOD
IS
    '未来行权日待偿期';
COMMENT ON COLUMN ASSET_DAILY_INFO.EX_PENDING_PERIOD_UNIT
IS
    '未来行权日待偿期单位（D/Y）';	
COMMENT ON COLUMN ASSET_DAILY_INFO.CREATE_USER
IS
    '创建人';
COMMENT ON COLUMN ASSET_DAILY_INFO.CREATE_DEPT
IS
    '创建部门';
COMMENT ON COLUMN ASSET_DAILY_INFO.CREATE_TIME
IS
    '创建时间';
COMMENT ON COLUMN ASSET_DAILY_INFO.UPDATE_USER
IS
    '更新人';
COMMENT ON COLUMN ASSET_DAILY_INFO.UPDATE_TIME
IS
    '更新时间'; 
